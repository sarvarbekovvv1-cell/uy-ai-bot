"""Pydantic schemas for property valuation input, output, and safe LLM explanation."""

from decimal import Decimal
from typing import Literal, Self

from pydantic import BaseModel, Field, field_validator, model_validator


class PropertyValuationInput(BaseModel):
    """Validated input parameters for property market valuation."""

    listing_type: Literal["sale", "rent"] = Field(
        description="Transaction category: sale or rent."
    )
    property_type: Literal["apartment", "house", "commercial", "land"] = Field(
        description="Property classification. Residential (apartment, house) supported for MVP."
    )
    region: str = Field(
        min_length=2, max_length=100, description="Province or city (e.g. Toshkent shahri)."
    )
    district: str = Field(
        min_length=2, max_length=100, description="City district (e.g. Chilonzor)."
    )
    total_area: Decimal = Field(
        gt=Decimal("0"), le=Decimal("10000"), description="Total area in square meters."
    )
    rooms: int = Field(ge=1, le=50, description="Total room count.")
    condition: Literal["new", "renovated", "needs_renovation", "shell"] | None = Field(
        default=None, description="Physical state/finish of the property."
    )
    floor: int | None = Field(default=None, ge=1, le=100, description="Floor level of apartment.")
    total_floors: int | None = Field(
        default=None, ge=1, le=100, description="Total building floors."
    )
    construction_type: Literal["brick", "panel", "monolith"] | None = Field(
        default=None, description="Building structural material."
    )
    has_furniture: bool | None = Field(default=None, description="Whether furniture is included.")
    currency: Literal["USD", "UZS"] = Field(
        default="USD", description="Target currency for valuation."
    )
    property_id: int | None = Field(
        default=None,
        gt=0,
        description="Optional ID of subject property to exclude from comparables.",
    )

    @model_validator(mode="after")
    def validate_floor_vs_total(self) -> Self:
        if (
            self.floor is not None
            and self.total_floors is not None
            and self.floor > self.total_floors
        ):
            msg = f"Floor ({self.floor}) cannot exceed total floors ({self.total_floors})"
            raise ValueError(msg)
        return self

    @field_validator("total_area")
    @classmethod
    def validate_total_area(cls, v: Decimal) -> Decimal:
        if v <= Decimal("0"):
            raise ValueError("Total area must be strictly positive")
        return v


class SafeComparableProperty(BaseModel):
    """Sanitized public-only data representation of a comparable property listing.

    Strictly guarantees NO owner PII, customer PII, phone numbers,
    Telegram IDs, or internal broker notes.
    """

    id: int
    title: str | None = None
    district: str
    region: str
    rooms: int
    total_area: Decimal
    price: Decimal
    currency: str
    price_per_m2: Decimal
    condition: str | None = None
    floor: int | None = None
    total_floors: int | None = None
    similarity_score: float = Field(default=1.0, ge=0.0, le=1.0)


class ValuationExplanation(BaseModel):
    """Safe, structured explanation generated by Gemini AI or fallback templates.

    CRITICAL ARCHITECTURAL GUARANTEE:
    This schema contains NO authoritative numeric price fields.
    Gemini is structurally forbidden from altering the engine's price output.
    """

    summary: str = Field(description="Concise summary explaining the price valuation range.")
    positive_factors: list[str] = Field(
        default_factory=list, description="Characteristics enhancing value."
    )
    negative_factors: list[str] = Field(
        default_factory=list, description="Characteristics dampening value."
    )
    missing_information: list[str] = Field(
        default_factory=list, description="Missing details that could improve precision."
    )
    recommendation: str = Field(description="Actionable advice for the property owner/buyer.")


class ValuationSafeContext(BaseModel):
    """Safe, sanitized context payload passed to Gemini for generating explanations.

    Guarantees no PII or sensitive credentials.
    """

    listing_type: str
    property_type: str
    region: str
    district: str
    rooms: int
    total_area: Decimal
    condition: str | None = None
    floor: int | None = None
    total_floors: int | None = None
    currency: str
    estimated_price_range_str: str
    central_price_str: str
    median_price_per_m2_str: str | None = None
    confidence: str
    comparable_count: int
    comparison_tier: int
    factors: list[str]
    warnings: list[str]


class PropertyValuationResult(BaseModel):
    """Authoritative output of the deterministic ValuationEngine."""

    estimated_price: Decimal | None = Field(
        default=None, description="Authoritative central market price estimate."
    )
    estimated_min_price: Decimal | None = Field(
        default=None, description="Estimated lower bound of market price range."
    )
    estimated_max_price: Decimal | None = Field(
        default=None, description="Estimated upper bound of market price range."
    )
    currency: str = Field(description="Currency denomination (USD or UZS).")
    confidence: Literal["low", "medium", "high"] = Field(
        description="Deterministic confidence classification."
    )
    comparable_count: int = Field(
        ge=0, description="Total number of approved comparable listings analyzed."
    )
    median_price_per_m2: Decimal | None = Field(
        default=None, description="Median price per square meter from comparables."
    )
    comparison_tier: int = Field(
        default=1,
        ge=1,
        le=3,
        description="Tier used: 1=exact district/rooms/area, 2=district wider, 3=region.",
    )
    factors: list[str] = Field(default_factory=list, description="List of key valuation drivers.")
    warnings: list[str] = Field(
        default_factory=list, description="List of reliability warnings or data limitations."
    )
    insufficient_data: bool = Field(
        default=False, description="Flag indicating insufficient comparable evidence."
    )
    comparable_properties: list[SafeComparableProperty] = Field(
        default_factory=list, description="Top approved comparables used."
    )
    explanation: ValuationExplanation | None = Field(
        default=None, description="Safe narrative explanation from Gemini or fallback."
    )
